function TABLE(head, rows, widths, o = {}) {
  const tw = widths.reduce((a, b) => a + b, 0);
  const bd = { style: BorderStyle.SINGLE, size: 4, color: LINE };
  const cell = (t, i, h) => new TableCell({ width: { size: widths[i], type: WidthType.DXA }, margins: { top: 60, bottom: 60, left: 100, right: 100 },
    shading: h ? { type: ShadingType.CLEAR, fill: HEAD_BG, color: 'auto' } : undefined, borders: { top: bd, bottom: bd, left: bd, right: bd },
    children: String(t).split('\n').map(line => new Paragraph({ children: runs(line, { size: o.size || 18, color: INK }).map(r => h ? new TextRun({ text: line.replace(/\*\*/g, ''), bold: true, font: FONT, size: o.size || 18 }) : r).slice(0, h ? 1 : undefined),
      alignment: (o.right || []).includes(i) && !h ? AlignmentType.RIGHT : AlignmentType.LEFT })) });
  return new Table({ width: { size: tw, type: WidthType.DXA }, columnWidths: widths,
    rows: [new TableRow({ tableHeader: true, children: head.map((t, i) => cell(t, i, true)) }), ...rows.map(r => new TableRow({ children: r.map((t, i) => cell(t, i, false)) }))] });
}
function IMG(file, wpx, caption) {
  const buf = fs.readFileSync(file); const w0 = buf.readUInt32BE(16), h0 = buf.readUInt32BE(20);   // PNG 크기
  const out = [new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 60, after: 60 }, children: [new ImageRun({ type: 'png', data: buf, transformation: { width: wpx, height: Math.round(wpx * h0 / w0) },
    altText: { title: caption || 'figure', description: caption || 'figure', name: 'fig' } })] })];
  if (caption) out.push(new Paragraph({ alignment: AlignmentType.CENTER, children: runs(caption, { size: 17, color: MUTED }), spacing: { after: 200 } }));
  return out;
}
