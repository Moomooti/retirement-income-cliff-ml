function runs(text, o = {}) {
  return String(text).split(/(\*\*[^*]+\*\*)/).filter(Boolean).map(s =>
    s.startsWith('**') ? new TextRun({ text: s.slice(2, -2), bold: true, font: FONT, size: o.size, color: o.color || INK })
                       : new TextRun({ text: s, font: FONT, size: o.size, color: o.color || INK, italics: o.italics }));
}
